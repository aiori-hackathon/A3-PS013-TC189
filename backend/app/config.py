"""Application configuration loaded from environment variables / .env."""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

PROJECT_ROOT = Path(__file__).resolve().parents[2]
BACKEND_ROOT = PROJECT_ROOT / "backend"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=str(PROJECT_ROOT / ".env"),
        env_file_encoding="utf-8",
        extra="ignore",
        case_sensitive=False,
    )

    app_name: str = "CyberTrace"
    environment: str = "development"
    api_prefix: str = "/api"
    log_level: str = "INFO"

    # No credential is embedded in code. DATABASE_URL must be supplied via .env
    # or the process environment.
    database_url: str
    test_database_url: str | None = None

    storage_root: Path = Field(default=BACKEND_ROOT / "storage")
    max_upload_size_bytes: int = 50 * 1024 * 1024
    max_line_bytes: int = 1024 * 1024
    max_stored_raw_line_chars: int = 8000
    max_parsing_issues: int = 10000
    allowed_extensions: str = ".log,.txt,.auth,.access,.out,.audit"
    cors_origins: str = ""

    # Phase 2 endpoint collection. Registration is disabled when the enrollment
    # token is unset. Agent API tokens are always generated by the server and
    # stored as SHA-256 hashes.
    agent_enrollment_token: str | None = None
    agent_stale_after_seconds: int = 300
    agent_default_heartbeat_interval_seconds: int = 60
    agent_default_collection_interval_seconds: int = 60
    agent_batch_max_files: int = 50
    agent_batch_max_bytes: int = 50 * 1024 * 1024
    agent_manifest_max_bytes: int = 512 * 1024
    quality_default_window_hours: int = 24

    @field_validator("storage_root", mode="after")
    @classmethod
    def _resolve_storage_root(cls, value: Path) -> Path:
        if not value.is_absolute():
            value = PROJECT_ROOT / value
        return value.resolve()

    @field_validator("max_upload_size_bytes")
    @classmethod
    def _check_upload_limit(cls, value: int) -> int:
        if value < 1024:
            raise ValueError("MAX_UPLOAD_SIZE_BYTES must be at least 1024 bytes")
        if value > 1024 * 1024 * 1024:
            raise ValueError("MAX_UPLOAD_SIZE_BYTES must not exceed 1 GiB")
        return value

    @field_validator("max_line_bytes")
    @classmethod
    def _check_line_limit(cls, value: int) -> int:
        if value < 1024:
            raise ValueError("MAX_LINE_BYTES must be at least 1024")
        return value

    @field_validator("max_parsing_issues")
    @classmethod
    def _check_issue_limit(cls, value: int) -> int:
        if value < 1:
            raise ValueError("MAX_PARSING_ISSUES must be positive")
        return value

    @field_validator("allowed_extensions")
    @classmethod
    def _check_extensions(cls, value: str) -> str:
        extensions = []
        for item in value.split(","):
            item = item.strip().lower()
            if not item:
                continue
            if not item.startswith("."):
                item = "." + item
            extensions.append(item)
        if not extensions:
            raise ValueError("ALLOWED_EXTENSIONS must contain at least one extension")
        return ",".join(extensions)

    @field_validator("agent_enrollment_token")
    @classmethod
    def _check_enrollment_token(cls, value: str | None) -> str | None:
        if value is None:
            return None
        value = value.strip()
        if not value:
            return None
        if len(value) < 24:
            raise ValueError("AGENT_ENROLLMENT_TOKEN must contain at least 24 characters")
        return value

    @field_validator("agent_stale_after_seconds")
    @classmethod
    def _check_stale_after(cls, value: int) -> int:
        if not 5 <= value <= 86400:
            raise ValueError("AGENT_STALE_AFTER_SECONDS must be between 5 and 86400")
        return value

    @field_validator(
        "agent_default_heartbeat_interval_seconds",
        "agent_default_collection_interval_seconds",
    )
    @classmethod
    def _check_agent_intervals(cls, value: int) -> int:
        if not 5 <= value <= 86400:
            raise ValueError("agent default intervals must be between 5 and 86400")
        return value

    @field_validator("agent_batch_max_files")
    @classmethod
    def _check_batch_files(cls, value: int) -> int:
        if not 1 <= value <= 200:
            raise ValueError("AGENT_BATCH_MAX_FILES must be between 1 and 200")
        return value

    @field_validator("agent_batch_max_bytes")
    @classmethod
    def _check_batch_bytes(cls, value: int) -> int:
        if not 1024 <= value <= 1024 * 1024 * 1024:
            raise ValueError("AGENT_BATCH_MAX_BYTES must be between 1024 and 1 GiB")
        return value

    @field_validator("agent_manifest_max_bytes")
    @classmethod
    def _check_manifest_bytes(cls, value: int) -> int:
        if not 1024 <= value <= 4 * 1024 * 1024:
            raise ValueError("AGENT_MANIFEST_MAX_BYTES must be between 1024 and 4 MiB")
        return value

    @field_validator("quality_default_window_hours")
    @classmethod
    def _check_quality_window(cls, value: int) -> int:
        if not 1 <= value <= 720:
            raise ValueError("QUALITY_DEFAULT_WINDOW_HOURS must be between 1 and 720")
        return value

    @property
    def allowed_extension_set(self) -> set[str]:
        return {item.strip() for item in self.allowed_extensions.split(",") if item.strip()}

    @property
    def cors_origin_list(self) -> list[str]:
        return [item.strip() for item in self.cors_origins.split(",") if item.strip()]

    @property
    def evidence_root(self) -> Path:
        return self.storage_root / "evidence"

    @property
    def temp_root(self) -> Path:
        return self.storage_root / "tmp"


@lru_cache
def get_settings() -> Settings:
    return Settings()
